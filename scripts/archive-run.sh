#!/bin/bash
# Выгрузка сырья в объектное хранилище. Запускается launchd раз в шесть часов.
#
# Отдельным заданием, а не хвостом ночного прогона: прогон живёт сутками
# и завершается редко, а сырьё копится непрерывно — за сутки сбора это
# гигабайт с лишним. Ждать конца прогона значило бы держать единственную
# копию на одном диске всё это время.
#
# Второй экземпляр launchd не запустит, пока идёт первый, а выгрузка идёт
# разницей по sha256 — значит частые запуски дёшевы и безопасны.
#
# Ключи берутся из .env в корне репозитория; поэтому cd, а не абсолютные пути.

set -u
cd "$(dirname "$0")/.." || exit 1

export PATH="/opt/homebrew/opt/postgresql@18/bin:/opt/homebrew/bin:$PATH"

LOG="logs/archive-$(date +%Y-%m-%d).log"
{
  echo "=== старт $(date '+%F %T') ==="
  .venv/bin/python -m harvester archive
  echo "=== стоп  $(date '+%F %T') ==="
} >> "$LOG" 2>&1
