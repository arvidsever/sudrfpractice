#!/bin/bash
# Свод карточек: тексты актов, участники, движение, путь жалобы.
#
# Объём выбран владельцем 27.08.2026: дела со ссылкой на акт, с 2025 года —
# 364 001 дело, около восьми суток при 2 000 запросах в час. Прайс-лист
# остальных вариантов — в docs/roadmap.md, этап 5. Глубину можно добрать
# потом: фильтры складываются, а свод возобновляемый и ничего
# не перекачивает — берутся дела с непроставленным card_fetched_at.
#
# Запускается launchd каждые полчаса. Второй заход не начнётся, пока идёт
# первый: харвестер держит замок на машину (flock), иначе два обхода дали
# бы двойной темп на ГАС и 429, как 20.08.2026.
#
# Прогон сам заканчивается кругом, в котором ни один суд не отдал карточек:
# значит все придержаны — и лучше выйти, чем крутиться вхолостую. Через
# полчаса launchd поднимет снова, и паузы судов к тому времени истекут.

set -u
cd "$(dirname "$0")/.." || exit 1

export PATH="/opt/homebrew/opt/postgresql@18/bin:/opt/homebrew/bin:$PATH"

LOG="logs/cards-$(date +%Y-%m-%d).log"
{
  echo "=== старт $(date '+%F %T') ==="
  caffeinate -i .venv/bin/python -m harvester cards --all --with-act --since 01.01.2025
  echo "=== стоп  $(date '+%F %T') ==="
} >> "$LOG" 2>&1
