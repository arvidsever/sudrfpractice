#!/bin/bash
# Суточный добег: индекс собран целиком, но суды публикуют каждый день,
# и без этого он застывает на дате последнего прогона очереди.
#
# Окно с запасом назад, а не «со вчера»: портал публикует и задним числом,
# и дело, попавшее в ленту через неделю после решения, окном в сутки
# не поймать. Неделя стоит около 600 запросов в день — четверть часа
# при общем дросселе, дешевле любого пропуска.

set -u
cd "$(dirname "$0")/.." || exit 1

export PATH="/opt/homebrew/opt/postgresql@18/bin:/opt/homebrew/bin:$PATH"

LOG="logs/catchup-$(date +%Y-%m-%d).log"
{
  echo "=== старт $(date '+%F %T') ==="
  caffeinate -i .venv/bin/python -m harvester catchup --days 7
  echo "=== стоп  $(date '+%F %T') ==="
} >> "$LOG" 2>&1
